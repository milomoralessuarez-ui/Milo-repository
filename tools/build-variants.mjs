/**
 * Assembles assets/js/variants.js from remix metadata files.
 *
 *   node tools/build-variants.mjs <entries-dir>
 *
 * Each JSON file in the directory holds an array of entries:
 *   { base, id, title, emo, speed, hue, sat, tagline, description, colors, tags }
 * Entries are validated (unique ids, existing bases, sane ranges), sorted by
 * base id, and written as Milo.registerVariant calls. The seed remixes that
 * shipped with the engine are kept.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-variants.mjs <entries-dir>'); process.exit(1); }

const SEED = [
  {
    base: 'neon-snake', id: 'neon-snake-turbo', title: 'Neon Snake Turbo', emo: '⚡', speed: 1.45, hue: 140,
    tagline: 'The classic snake at half-second reaction times',
    description: 'Neon Snake with the throttle wedged open: the grid is the same, the apples are the same, but everything moves at almost half again the pace, so a route you could plan in the original has to come from instinct here. Scores are kept on their own leaderboard — a hundred points in Turbo is worth bragging about.',
    colors: ['#052e16', '#4ade80'], tags: ['snake', 'turbo', 'reflex', 'remix'],
  },
  {
    base: 'brick-breaker', id: 'brick-breaker-zen', title: 'Brick Breaker Zen', emo: '🧘', speed: 0.75, hue: 300,
    tagline: 'Slow-motion brick breaking for unwinding',
    description: 'Brick Breaker at three-quarter speed in a violet palette. The ball floats, the paddle glides, and there is time to line up every rebound properly — a version for playing with a cup of tea rather than white knuckles. Same bricks, same power-ups, its own best score.',
    colors: ['#2e1065', '#e879f9'], tags: ['breakout', 'zen', 'relaxing', 'remix'],
  },
];

const gamesDir = resolve(ROOT, 'assets/js/games');
const baseIds = new Set();
for (const f of (await readdir(gamesDir)).filter((n) => n.endsWith('.js'))) {
  const src = await readFile(resolve(gamesDir, f), 'utf8');
  for (const m of src.matchAll(/id:\s*'([a-z0-9-]+)'/g)) baseIds.add(m[1]);
}

const entries = [...SEED];
for (const f of (await readdir(dir)).filter((n) => n.endsWith('.json')).sort()) {
  const arr = JSON.parse(await readFile(resolve(dir, f), 'utf8'));
  const list = Array.isArray(arr) ? arr : arr.entries;
  entries.push(...list);
}

const seen = new Set();
const problems = [];
const HEX = /^#[0-9a-f]{6}$/i;
for (const e of entries) {
  const where = `${e.id || '?'} (${e.base || '?'})`;
  if (!e.id || !/^[a-z0-9-]+$/.test(e.id)) problems.push(`${where}: bad id`);
  if (seen.has(e.id)) problems.push(`${where}: duplicate id`);
  seen.add(e.id);
  if (!baseIds.has(e.base)) problems.push(`${where}: unknown base`);
  if (baseIds.has(e.id)) problems.push(`${where}: id collides with a base game`);
  if (!e.title || !e.tagline || !e.description || e.description.length < 120) problems.push(`${where}: thin copy`);
  if (!(e.speed >= 0.5 && e.speed <= 2.2)) problems.push(`${where}: speed out of range`);
  if (!(e.hue >= 0 && e.hue < 360)) problems.push(`${where}: hue out of range`);
  if (!Array.isArray(e.colors) || e.colors.length !== 2 || !e.colors.every((c) => HEX.test(c))) problems.push(`${where}: colors must be two hex values`);
  if (!Array.isArray(e.tags) || e.tags.length < 2) problems.push(`${where}: needs tags`);
  if (!e.emo) problems.push(`${where}: needs emo`);
}
if (problems.length) {
  console.error(`${problems.length} problem(s):\n  ` + problems.join('\n  '));
  process.exit(1);
}

entries.sort((a, b) => a.base.localeCompare(b.base) || a.id.localeCompare(b.id));

const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const lines = entries.map((e) =>
  `  V(${q(e.base)}, { id: ${q(e.id)}, title: ${q(e.title)}, emo: ${q(e.emo)}, speed: ${e.speed}, hue: ${e.hue}` +
  (e.sat ? `, sat: ${e.sat}` : '') +
  `,\n    tagline: ${q(e.tagline)},\n    description: ${q(e.description)},\n` +
  `    colors: [${q(e.colors[0])}, ${q(e.colors[1])}], tags: [${e.tags.map(q).join(', ')}] });`
);

const out = `/* ==========================================================================
   MiloPlay remixes
   Data-driven variants of base games: each entry is a real catalogue entry
   with its own title, description, thumbnail and high-score slot, retuned
   through \`speed\` (game-time multiplier) and restyled through \`hue\`/\`sat\`.
   Loaded after every base game file — see Milo.registerVariant in engine.js.
   Generated by tools/build-variants.mjs; ${entries.length} remixes.
   ========================================================================== */
(function () {
  'use strict';
  var V = window.Milo.registerVariant;

${lines.join('\n\n')}
})();
`;

await writeFile(resolve(ROOT, 'assets/js/variants.js'), out);
console.log(`wrote assets/js/variants.js with ${entries.length} remixes`);
